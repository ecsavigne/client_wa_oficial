package message

type Button struct {
	Id    string `json:"id"`    //  Don't have space begin or end ofof id of button, max 256 characters
	Type  string `json:"type"`  // Only type "reply"(in buttons response)
	Title string `json:"title"` // Don't empty string and max 20 characters. Must be unique within the message. Emoji support is offered, but not Markdown. Maximum length: 20 characters.
}

type Row struct {
	Id          string `json:"id" validate:"required"`    // Required, .Longitude <= 24 characters
	Title       string `json:"title" validate:"required"` // Required, .Longitude <= 200 characters
	Description string `json:"description,omitempty"`     // Optional, .Longitude <= 72 characters
}

